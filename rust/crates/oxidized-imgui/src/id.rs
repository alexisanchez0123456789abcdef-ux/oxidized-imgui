//! Identifier hashing.
//!
//! Bit-compatible with Dear ImGui 1.93.1 (`imgui.cpp`, `ImHashStr`/`ImHashData`):
//! CRC32c (Castagnoli, reflected), seeded, and `###` restarts the hash from the seed so that
//! `"label###id"` hashes like `"id"`.
//!
//! The constants in the tests are produced by the C++ reference in `rust/tools/oracle`, not by
//! this code: they are the compatibility contract.

/// A widget identifier, `unsigned int` in the C++ reference.
pub type ImGuiID = u32;

/// CRC32c (Castagnoli) reflected lookup table, generated at compile time.
///
/// The reference spells the same table out in `imgui.cpp` (`GCrc32LookupTable`).
const CRC32C_TABLE: [u32; 256] = build_table();

const fn build_table() -> [u32; 256] {
    let mut table = [0u32; 256];
    let mut i = 0usize;
    while i < 256 {
        let mut crc = i as u32;
        let mut bit = 0;
        while bit < 8 {
            crc = if crc & 1 != 0 {
                (crc >> 1) ^ 0x82F6_3B78
            } else {
                crc >> 1
            };
            bit += 1;
        }
        table[i] = crc;
        i += 1;
    }
    table
}

#[inline]
fn feed(crc: u32, byte: u8) -> u32 {
    (crc >> 8) ^ CRC32C_TABLE[((crc & 0xFF) ^ byte as u32) as usize]
}

/// Hashes a byte slice with a known length. `###` has no special meaning here, as upstream.
pub fn hash_data(data: &[u8], seed: ImGuiID) -> ImGuiID {
    let mut crc = !seed;
    for &byte in data {
        crc = feed(crc, byte);
    }
    !crc
}

/// Hashes a zero-terminated string: `###` resets the hash back to `seed`.
pub fn hash_str(data: &[u8], seed: ImGuiID) -> ImGuiID {
    let seed = !seed;
    let mut crc = seed;
    let mut i = 0usize;
    while i < data.len() {
        let c = data[i];
        if c == b'#' && i + 2 < data.len() && data[i + 1] == b'#' && data[i + 2] == b'#' {
            crc = seed;
            i += 3;
            continue;
        }
        crc = feed(crc, c);
        i += 1;
    }
    !crc
}

/// [`hash_str`] for text; the reference hashes the UTF-8 bytes it is given.
pub fn hash_str_utf8(text: &str, seed: ImGuiID) -> ImGuiID {
    hash_str(text.as_bytes(), seed)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Generated by the C++ reference: `rust/tools/oracle` prints exactly these lines.
    const ORACLE: &[(ImGuiID, &str, ImGuiID)] = &[
        (0, "", 0),
        (0, "Hello", 2178485787),
        (0, "Window", 4197362180),
        (0, "##DragDropCancelHandler", 369297806),
        (0, "label###id", 1494682982),
        (0, "a###b###c", 552285127),
        (0, "###", 0),
        (12345, "Hello", 3596884756),
        (0xFFFF_FFFF, "abc", 2849006386),
        (0, "café", 2636418872),
        (0, "😀", 3823164276),
        (0x1111_1111, "ViewportDefault", 3667934776),
    ];

    #[test]
    fn table_matches_reference() {
        assert_eq!(CRC32C_TABLE[0], 0x0000_0000);
        assert_eq!(CRC32C_TABLE[1], 0xF26B_8303);
        assert_eq!(CRC32C_TABLE[255], 0xAD7D_5351);
    }

    #[test]
    fn hashes_match_oracle() {
        for &(seed, text, expected) in ORACLE {
            assert_eq!(
                hash_str_utf8(text, seed),
                expected,
                "seed={seed} text={text:?}"
            );
        }
    }

    #[test]
    fn triple_hash_resets_to_seed() {
        assert_eq!(hash_str_utf8("label###id", 0), hash_str_utf8("id", 0));
        assert_eq!(hash_str_utf8("###id", 0), hash_str_utf8("id", 0));
        assert_eq!(hash_str_utf8("a###b###c", 0), hash_str_utf8("c", 0));
    }

    #[test]
    fn data_and_str_agree_on_known_length() {
        for &(seed, text, _) in ORACLE {
            if text.contains("###") {
                continue;
            }
            assert_eq!(hash_data(text.as_bytes(), seed), hash_str_utf8(text, seed));
        }
    }
}
